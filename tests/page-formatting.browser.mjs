import assert from "node:assert/strict";
import { mkdtemp, cp, symlink, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import path from "node:path";
import { spawn } from "node:child_process";
import { createRequire } from "node:module";
import bcrypt from "bcryptjs";
import { PGlite } from "@electric-sql/pglite";
import { drizzle } from "drizzle-orm/pglite";
import { migrate } from "drizzle-orm/pglite/migrator";
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || "playwright");
const folder = await mkdtemp(path.join(tmpdir(), "vinyasa-page-formatting-"));
const base = "http://localhost:3197";
let browser, server;
let output = "";
try {
  const pg = new PGlite(path.join(folder, "db"));
  await migrate(drizzle(pg), { migrationsFolder: "./drizzle" });
  await pg.query("INSERT INTO admin_users (email, password_hash) VALUES ($1, $2)", ["formatting-test@example.com", await bcrypt.hash("test-only-password", 4)]);
  await pg.close();
  await cp(".next", path.join(folder, ".next"), { recursive: true, filter: source => !source.split(path.sep).includes("cache") });
  await cp("package.json", path.join(folder, "package.json"));
  await cp("next.config.mjs", path.join(folder, "next.config.mjs"));
  await symlink(path.resolve("node_modules"), path.join(folder, "node_modules"), "junction");
  await symlink(path.resolve("public"), path.join(folder, "public"), "junction");
  server = spawn(process.execPath, [path.resolve("node_modules/next/dist/bin/next"), "start", "-p", "3197"], { cwd: folder, env: { ...process.env, DATABASE_URL: `pglite:${path.join(folder, "db")}`, SESSION_SECRET: "isolated-formatting-test-secret" }, stdio: "pipe" });
  server.stdout.on("data", chunk => output += chunk);
  server.stderr.on("data", chunk => output += chunk);
  let ready = false;
  for (let i = 0; i < 90; i++) {
    if (server.exitCode !== null) throw Error(output.slice(-2000));
    try { if ((await fetch(base + "/admin/login")).ok) { ready = true; break; } } catch {}
    await new Promise(resolve => setTimeout(resolve, 1000));
  }
  assert.ok(ready, "isolated server starts");
  browser = await chromium.launch({ headless: true, ...(process.env.CHROMIUM_EXECUTABLE ? { executablePath: process.env.CHROMIUM_EXECUTABLE } : {}) });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  const page = await context.newPage();
  page.setDefaultTimeout(30000);
  const errors = [];
  page.on("pageerror", error => errors.push(error.message));
  await page.goto(base + "/work-from-farm", { waitUntil: "networkidle" });
  assert.equal(await page.locator("details").count(), 8, "all 8 FAQs are present");
  const text = await page.locator("body").textContent();
  for (const phrase of ["under a tree, in a gazebo", "There is no fixed program or schedule", "sprouts and fruits", "raita, chaach, papad", "Washing your own plate", "Anyone comfortable with simple, community-based living", "15 nights or longer", "Basic power backup is available", "Check Availability & Book"]) assert.ok(text.includes(phrase), phrase);
  await page.screenshot({ path: path.join(folder, "work-from-farm-desktop.png"), fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1), "no mobile horizontal overflow");
  await page.screenshot({ path: path.join(folder, "work-from-farm-mobile.png"), fullPage: true });
  console.log("PASS: full Work from Farm content, eight FAQs, desktop and mobile layout");
  await page.setViewportSize({ width: 1440, height: 1000 });
  const login = await context.request.post(base + "/api/admin/login", { data: { email: "formatting-test@example.com", password: "test-only-password" } });
  assert.equal(login.status(), 200);
  await page.goto(base + "/admin/pages/site/work-from-farm");
  const field = page.locator('input[name="Content.introduction / 1"]').locator("..");
  await field.getByRole("button", { name: "Format text", exact: true }).click();
  const editor = field.locator(".ProseMirror");
  await editor.click(); await editor.press("Control+a");
  await field.locator('button[title="Bold"]').click();
  await field.getByLabel("Font family").selectOption("Georgia");
  await field.locator('button[title="Text colour #8f3b31"]').click();
  page.once("dialog", dialog => dialog.accept("https://example.com/work-from-farm"));
  await field.locator('button[title="Add / edit link"]').click();
  await page.getByRole("button", { name: "Save content", exact: true }).click();
  await page.getByRole("status").filter({ hasText: "Saved." }).waitFor();
  await page.reload();
  await page.locator('input[name="Content.introduction / 1"]').waitFor({ state: "attached" });
  assert.match(await page.locator('input[name="Content.introduction / 1"]').inputValue(), /<strong>/);
  const publicPage = await context.newPage();
  await publicPage.goto(base + "/work-from-farm");
  const formatted = publicPage.locator('a[href="https://example.com/work-from-farm"]');
  await formatted.waitFor();
  assert.ok(await formatted.locator("strong").count() > 0 || await formatted.evaluate(el => !!el.closest("strong")), "bold survives saving");
  const appearance = await formatted.evaluate(el => ({ colour: getComputedStyle(Array.from(el.querySelectorAll("*")).find(node => Array.from(node.childNodes).some(child => child.nodeType === 3 && child.textContent.trim())) || el).color, font: getComputedStyle(Array.from(el.querySelectorAll("*")).find(node => Array.from(node.childNodes).some(child => child.nodeType === 3 && child.textContent.trim())) || el).fontFamily, weight: getComputedStyle(Array.from(el.querySelectorAll("*")).find(node => Array.from(node.childNodes).some(child => child.nodeType === 3 && child.textContent.trim())) || el).fontWeight }));
  assert.equal(appearance.colour, "rgb(143, 59, 49)"); assert.match(appearance.font, /Georgia/); assert.ok(Number(appearance.weight) >= 700);
  console.log("PASS: existing-page bold, font family, colour and link save, reload and render");
  await page.goto(base + "/admin/pages/new");
  await page.locator('input[name="title"]').fill("Formatting browser test");
  await page.locator('input[name="slug"]').fill("formatting-browser-test");
  await page.locator('select[name="status"]').selectOption("published");
  await page.getByRole("button", { name: /^Paragraph Text with/ }).first().click();
  const newEditor = page.locator(".ProseMirror"); await newEditor.click(); await newEditor.press("Control+a"); await newEditor.pressSequentially("A formatted new page"); await newEditor.press("Control+a");
  await page.locator('button[title="Bold"]').click();
  await page.getByLabel("Font family").selectOption("Georgia");
  await page.locator('button[title="Text colour #6b7a5e"]').click();
  page.once("dialog", dialog => dialog.accept("/contact")); await page.locator('button[title="Add / edit link"]').click();
  await page.getByRole("button", { name: "Save page", exact: true }).click();
  await page.waitForURL(/\/admin\/pages$/);
  await publicPage.goto(base + "/formatting-browser-test");
  const newLink = publicPage.locator('main a[href="/contact"]').filter({ hasText: "A formatted new page" }); await newLink.waitFor();
  const newAppearance = await newLink.evaluate(el => ({ colour: getComputedStyle(Array.from(el.querySelectorAll("*")).find(node => Array.from(node.childNodes).some(child => child.nodeType === 3 && child.textContent.trim())) || el).color, font: getComputedStyle(Array.from(el.querySelectorAll("*")).find(node => Array.from(node.childNodes).some(child => child.nodeType === 3 && child.textContent.trim())) || el).fontFamily, weight: getComputedStyle(Array.from(el.querySelectorAll("*")).find(node => Array.from(node.childNodes).some(child => child.nodeType === 3 && child.textContent.trim())) || el).fontWeight }));
  assert.equal(newAppearance.colour, "rgb(107, 122, 94)"); assert.match(newAppearance.font, /Georgia/); assert.ok(Number(newAppearance.weight) >= 700);
  assert.deepEqual(errors, []);
  console.log("PASS: new-page bold, font family, colour and link publish and render");
  console.log("Browser artifacts: " + folder);
} catch (error) { await writeFile(path.join(folder, "server.log"), output); console.error("Browser test artifacts: " + folder); throw error; }
finally { await browser?.close(); server?.kill(); }
